-- 書式は CREATE TABLE テーブル名 ( ... ); を前提とする。
-- DBへの実行は不要。解析ツールのテーブル名照合に使うサンプル。

-- ENT01:注文
CREATE TABLE ORDERS (
    ORDER_ID BIGINT PRIMARY KEY,
    CUSTOMER_ID BIGINT,
    PROCESSED INTEGER DEFAULT 0
);

CREATE TABLE SECRET_AUDIT (
    ID BIGINT PRIMARY KEY
);

CREATE TABLE SHOULD_NOT_APPEAR (
    ID BIGINT PRIMARY KEY
);

-- ENT02:顧客
CREATE TABLE CUSTOMERS (
    CUSTOMER_ID BIGINT PRIMARY KEY
);

-- ENT03:注文明細
CREATE TABLE ORDER_ITEMS (
    ITEM_ID BIGINT PRIMARY KEY,
    PRODUCT_ID BIGINT,
    ORDER_ID BIGINT
);

CREATE TABLE ORDER_ARCHIVE (
    ORDER_ID BIGINT PRIMARY KEY,
    CUSTOMER_ID BIGINT
);

-- ENT05:在庫
CREATE TABLE INVENTORY (
    PRODUCT_ID BIGINT PRIMARY KEY,
    QUANTITY INTEGER DEFAULT 0
);

-- ENT04:ユーザー
CREATE TABLE USERS (
    USER_ID BIGINT PRIMARY KEY
);

-- ジョブ共通の登録時刻管理テーブル。図では各ジョブの下へ同じ表を再表示する。
-- ENT08:登録管理
CREATE TABLE REGISTRATION_MANAGE (
    JOB_ID VARCHAR(32),
    REGISTERED_AT TIMESTAMP
);

-- ENT06:配送依頼
CREATE TABLE SHIPPING_REQUESTS (
    ORDER_ID BIGINT PRIMARY KEY,
    CUSTOMER_ID BIGINT,
    STATUS VARCHAR(16)
);

-- ENT07:出荷
CREATE TABLE SHIPMENTS (
    ORDER_ID BIGINT PRIMARY KEY,
    SHIPPED_AT TIMESTAMP
);
